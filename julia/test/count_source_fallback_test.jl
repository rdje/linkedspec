module JuliaCountSourceFallback
using LinkedSpecJulia, JSON3, Test

function strict_equal(actual, expected)
    if expected isa Bool
        return actual === expected
    elseif expected isa Number
        return actual isa Number && !(actual isa Bool) && actual == expected
    elseif expected === nothing
        return actual === nothing
    elseif expected isa AbstractString
        return actual isa AbstractString && actual == expected
    elseif expected isa AbstractVector
        return actual isa AbstractVector && length(actual) == length(expected) &&
            all(strict_equal(a, e) for (a, e) in zip(actual, expected))
    elseif expected isa AbstractDict
        return actual isa AbstractDict && Set(keys(actual)) == Set(keys(expected)) &&
            all(strict_equal(actual[key], value) for (key, value) in expected)
    end
    error("unexpected Count source fixture kind $(typeof(expected))")
end

function observe(row)
    source, input, label = row["source"], row["input"], row["id"]
    parsed = parse_spec_with_staged_user_function_definitions(source)
    compiled = compile_spec(parsed)
    restored = from_json(SpecFile, JSON3.read(JSON3.write(to_json(parsed))))
    emitted = emit_julia_source_v2(compiled, "count-source-fallback.spec")
    capture = get(ENV, "LINKEDSPEC_COUNT_SOURCE_CAPTURE", "")
    if !isempty(capture)
        # Retain actual generated bytes and public AST before loading or execution.
        write(joinpath(capture, label * ".jl"), emitted)
        write(joinpath(capture, label * ".ast.json"), JSON3.write(to_json(parsed)))
    end
    fresh = () -> begin
        host = Module(gensym(:CountSourceGenerated))
        Base.include_string(host, emitted)
        parser = Base.invokelatest(getfield, host, :LinkedSpecGeneratedParser)
        Base.invokelatest(Base.invokelatest(getfield, parser, :execute), input)
    end
    result = Dict{String,Any}()
    for (route, operation) in (
        "native" => () -> runtime_execute(LinkedSpecRuntimeEngine(compiled), input).value,
        "restored" => () -> runtime_execute(LinkedSpecRuntimeEngine(compile_spec(restored)), input).value,
        "plan" => () -> execute_generated_parser_v2(
            compiled, build_generated_rule_plan(compiled), input, "count-source-fallback.spec",
        ),
        "fresh" => fresh,
    )
        result[route] = try
            Dict("ok" => operation())
        catch failure
            Dict("error" => sprint(showerror, failure), "class" => string(nameof(typeof(failure))))
        end
    end
    return result
end

@testset "Julia initial Count source fallback" begin
    root = dirname(dirname(@__DIR__))
    cases = JSON3.read(read(joinpath(root, "tests", "fixtures", "count_boolean_source_cases.json"), String), Any)
    for row in cases
        @testset "$(row["id"])" begin
            actual = observe(row)
            println("COUNT_SOURCE_JULIA ", row["id"], " ", JSON3.write(actual))
            @test Set(keys(actual)) == Set(["native", "restored", "plan", "fresh"])
            for route in ("native", "restored", "plan", "fresh")
                if haskey(row, "expected_error")
                    @test occursin(row["expected_error"], get(actual[route], "error", ""))
                else
                    expected = get(row, "expected_nonperl", get(row, "expected", nothing))
                    @test haskey(actual[route], "ok") && strict_equal(actual[route]["ok"], expected)
                end
            end
        end
    end
end
end # module
